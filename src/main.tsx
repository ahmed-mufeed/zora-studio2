// استيراد وضع التدقيق الصارم (StrictMode) من مكتبة React لاكتشاف الأخطاء والممارسات غير الموصى بها أثناء التطوير
import { StrictMode } from "react";

// استيراد دالة إنشاء الجذر (Root) من React DOM المسؤولة عن ربط وتصيير شجرة مكونات التطبيق داخل متصفح الويب
import { createRoot } from "react-dom/client";

// استيراد ملف الأنماط والتنسيقات الشاملة للمشروع (Tailwind CSS والمتغيرات البصرية والحركات)
import "./index.css";

// استيراد المكوّن الجذري للتطبيق (App) الذي يحتوي على مزودات الحالة ونظام التوجيه والمسارات
